def sanitize_excel_cell(val):
    """Spreadsheet formula injection protection per security standard."""
    if isinstance(val, str) and val and val[0] in ("=", "+", "-", "@", "\t", "\r"):
        return "'" + val
    return val


def normalize_phone(p):
    return re.sub(r"[^0-9]", "", str(p or ""))


def normalize_name(name):
    s = unicodedata.normalize("NFKC", str(name or ""))
    s = re.sub(r"（.*?）|\(.*?\)", "", s)
    s = re.sub(r"[\s　・\-ー_]", "", s).lower()
    return s


def load_and_merge_stores():
    zone_files = sorted(glob.glob(ZONES_GLOB))
    raw_stores = []
    for zf in zone_files:
        with open(zf, "r", encoding="utf-8") as f:
            items = json.load(f)
            if isinstance(items, dict) and "stores" in items:
                items = items["stores"]
            for it in items:
                it["_zoneFile"] = os.path.basename(zf)
                raw_stores.append(it)

    seen_phones = set()
    seen_names = set()
    deduped = []

    for st in raw_stores:
        p_norm = normalize_phone(st.get("phone", ""))
        n_norm = normalize_name(st.get("name", ""))
        if not p_norm or not n_norm:
            continue
        if p_norm in seen_phones or n_norm in seen_names:
            continue
        seen_phones.add(p_norm)
        seen_names.add(n_norm)

        code = st.get("stationCode", "M11")
        if code not in STATION_META_MAP:
            code = "M16"
        grp, ride_min, fare_yen = STATION_META_MAP[code]
        st["stationCode"] = code
        st["stationGroup"] = grp
        st["rideFromEsakaMin"] = ride_min
        st["fareFromEsakaYen"] = fare_yen

        seg = st.get("segmentCode", "SEG2")
        if seg not in SEG_MAP:
            seg = "SEG2"
        st["segmentCode"] = seg
        st["segmentLabel"] = SEG_MAP[seg]

        st["rank"] = "S" if st.get("rank") == "S" else "A"
        walk = int(st.get("walkMinutes") or 5)
        st["walkMinutes"] = max(1, min(12, walk))

        phone_str = str(st.get("phone", "")).strip()
        if phone_str.startswith("06-"):
            st["phoneType"] = "直通(06)"
        elif phone_str.startswith("050-"):
            st["phoneType"] = "予約・案内番号(050)"
        else:
            st["phoneType"] = st.get("phoneType") or "店舗電話"

        # Clean internal helper key
        st.pop("_zoneFile", None)
        deduped.append(st)

    # Sort by station order M11 -> M16S, then Rank S -> A, then walkMinutes
    deduped.sort(
        key=lambda x: (
            STATION_ORDER.index(x["stationCode"]),
            0 if x["rank"] == "S" else 1,
            x["walkMinutes"],
            x["name"],
        )
    )

    for idx, st in enumerate(deduped, start=1):
        st["id"] = idx

    with open(MERGED_STORES_JSON, "w", encoding="utf-8") as f:
        json.dump(deduped, f, ensure_ascii=False, indent=2)

    return deduped


